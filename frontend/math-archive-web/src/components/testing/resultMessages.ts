const neutral = { title: "Тест завершено!", subtitle: "Твої відповіді збережено. Результати доступні відповідно до налаштувань тесту." };
export function resultPresentation(attemptId: string, percentage: number | null): ResultMessage & { band: ResultBand } {
  if (percentage === null || !Number.isFinite(percentage) || percentage < 0 || percentage > 100) return { ...neutral, band: "neutral" };
  const band = percentage === 100 ? "perfect" : percentage >= 80 ? "high" : percentage >= 60 ? "good" : percentage >= 40 ? "developing" : "practice";
  // Stable across browsers, renders and revisits; independent of time or random state.
  let hash = 2166136261;
  for (const character of attemptId) hash = Math.imul(hash ^ character.charCodeAt(0), 16777619) >>> 0;
  const choices = resultMessages[band];
  return { ...choices[hash % choices.length], band };
}
